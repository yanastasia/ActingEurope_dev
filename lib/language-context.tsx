// Provider component
export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en")

  // Load language preference from localStorage on mount
  useEffect(() => {
    const savedLanguage = localStorage.getItem("actingEurope_language") as Language
    if (savedLanguage && ["en", "bg", "mk", "sr"].includes(savedLanguage)) {
      setLanguageState(savedLanguage)
    }
  }, [])

  // Save language preference to localStorage when it changes
  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    localStorage.setItem("actingEurope_language", lang)
  }

  // Translation function with interpolation support
  const t = (key: string, params?: Record<string, any>): string => {
    let translation = translations[language][key as keyof (typeof translations)[typeof language]] || key
    
    // Handle interpolation if params are provided
    if (params && typeof translation === 'string') {
      Object.keys(params).forEach(paramKey => {
        const placeholder = `{${paramKey}}`
        translation = translation.replace(new RegExp(placeholder, 'g'), String(params[paramKey]))
      })
    }
    
    return translation
  }

  return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>
}

// Export translations object
export { translations }

// Custom hook to use the language context
export function useLanguage() {
  const context = useContext(LanguageContext)
  if (context === undefined) {
    throw new Error("useLanguage must be used within a LanguageProvider")
  }
  return context
}
